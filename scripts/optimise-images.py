#!/usr/bin/env python3
"""
Creates WebP copies of the gallery photographs and book covers.

Originals in public/images are never changed (they remain the fallback and
are still used for social-sharing images). WebP files are written to
public/images/optimised/ and their sizes recorded in
src/data/imageVariants.ts, which the components read.

Run again after adding or replacing an image:  python3 scripts/optimise-images.py
Requires Pillow (pip install Pillow).
"""
import json, os, re, sys
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, 'public')
OUT_DIR = os.path.join(PUBLIC, 'images', 'optimised')
MANIFEST = os.path.join(ROOT, 'src', 'data', 'imageVariants.ts')

def referenced(path_ts, key):
    text = open(os.path.join(ROOT, path_ts), encoding='utf-8').read()
    return sorted(set(re.findall(key + r':\s*"(/images/[^"]+)"', text)))

TARGETS = [(p, 1200) for p in referenced('src/data/galleryData.ts', 'imagePath')] + \
          [(p, 600) for p in referenced('src/data/booksData.ts', 'coverImage')]

os.makedirs(OUT_DIR, exist_ok=True)
manifest = {}
for src, max_w in TARGETS:
    file = os.path.join(PUBLIC, src.lstrip('/'))
    if not os.path.exists(file):
        print('missing, skipped:', src); continue
    try:
        im = ImageOps.exif_transpose(Image.open(file)).convert('RGB')
    except Exception as e:  # unreadable file: keep using the original
        print('unreadable, skipped:', src, e); continue
    if im.width > max_w:
        im = im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)
    name = re.sub(r'[^A-Za-z0-9_-]+', '-', os.path.splitext(os.path.relpath(file, os.path.join(PUBLIC, 'images')))[0]).strip('-')
    out = os.path.join(OUT_DIR, name + '.webp')
    im.save(out, 'WEBP', quality=80, method=6)
    before, after = os.path.getsize(file), os.path.getsize(out)
    if after > before * 0.85:  # under 15% smaller: keep the original only
        os.remove(out); print(f'kept original: {src}'); continue
    manifest[src] = {'src': '/images/optimised/' + name + '.webp', 'width': im.width, 'height': im.height}
    print(f'{src}: {before//1024} KB -> {after//1024} KB ({im.width}x{im.height})')

with open(MANIFEST, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/optimise-images.py — do not edit by hand.\n')
    f.write('// Maps an original image path to its optimised WebP copy.\n')
    f.write('export interface ImageVariant { src: string; width: number; height: number }\n\n')
    f.write('export const IMAGE_VARIANTS: Record<string, ImageVariant> = ' + json.dumps(manifest, indent=2, ensure_ascii=False) + ';\n\n')
    f.write('/** The optimised copy of a local image, or null to use the original. */\n')
    f.write('export const optimisedImage = (path: string): ImageVariant | null => IMAGE_VARIANTS[path] ?? null;\n')
print(len(manifest), 'variants written')
